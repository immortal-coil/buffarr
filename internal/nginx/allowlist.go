// Package nginx generates the Host-header CDN allow-list nginx's cache
// vhost uses to accept or reject requests (R9, KTD3), and writes it to the
// shared volume nginx's in-container file-watcher reloads from (KTD7). It
// also holds the PURGE client used by U5's delete path.
package nginx

import (
	"fmt"
	"net"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// hostnameRE matches a syntactically valid DNS hostname: labels of
// alphanumerics/hyphens, dot-separated, no leading/trailing hyphen per
// label. This is deliberately conservative -- a CDN domain that doesn't
// match is dropped rather than risking unescaped input reaching an nginx
// map{} fragment (see GenerateAllowlist).
var hostnameRE = regexp.MustCompile(`^[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?(\.[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?)+$`)

// allowlistHeader documents the generated file for anyone who reads it on
// disk; it is a comment, not part of the nginx grammar.
const allowlistHeader = "# Generated by internal/nginx.GenerateAllowlist. Do not edit by hand;\n" +
	"# this file is overwritten on every CDN toggle and re-read by nginx's\n" +
	"# in-container file watcher (KTD7).\n"

// AllowlistEntry is one CDN domain to allow by Host header. Wildcard
// mirrors dnsmasq's DomainKind split (internal/dnsmasq's Domain.Kind):
// some CDN platforms (e.g. Uplay) are wildcard-only at the DNS layer, so
// nginx's allow-list must accept the same subdomains dnsmasq resolves, or
// the two layers disagree and a legitimately-resolved client gets a 403.
type AllowlistEntry struct {
	Domain   string
	Wildcard bool
}

// GenerateAllowlist renders the Host-header allow-list `map` fragment for
// the given set of enabled CDN domains (KTD3, R9). The fragment defines
// $cdn_enabled: 1 for any Host matching an enabled domain, 0 otherwise
// (default-deny-by-omission); the cache vhost rejects requests where
// $cdn_enabled = 0 with 403.
//
// The `hostnames;` parameter and the leading-dot form (".domain") for
// Wildcard entries are required for nginx's map directive to treat a
// domain as a prefix mask rather than a literal string match -- confirmed
// live against a running nginx: without `hostnames;`, "*.domain" is just
// an inert string that never matches any real Host header.
//
// Domains that fail basic hostname validation are skipped rather than
// included verbatim -- they are untrusted-ish operator/backend input by the
// time they reach this function (KTD3's toggle path), and a malformed entry
// must not be able to break the generated nginx syntax (this is the second
// line of defense; the primary one is nginx -t validation before reload,
// see Watch). Skipped domains are returned alongside the fragment so the
// caller can log/report them.
func GenerateAllowlist(entries []AllowlistEntry) (fragment string, skipped []string) {
	type validEntry struct {
		domain   string
		wildcard bool
	}
	valid := make([]validEntry, 0, len(entries))
	seen := make(map[string]struct{}, len(entries))
	for _, e := range entries {
		d := strings.TrimSpace(strings.ToLower(e.Domain))
		if d == "" {
			continue
		}
		if !hostnameRE.MatchString(d) || looksLikeIP(d) {
			skipped = append(skipped, d)
			continue
		}
		if _, dup := seen[d]; dup {
			continue
		}
		seen[d] = struct{}{}
		valid = append(valid, validEntry{domain: d, wildcard: e.Wildcard})
	}

	sort.Slice(valid, func(i, j int) bool { return valid[i].domain < valid[j].domain })

	var b strings.Builder
	b.WriteString(allowlistHeader)
	b.WriteString("map $host $cdn_enabled {\n")
	b.WriteString("    hostnames;\n")
	b.WriteString("    default 0;\n")
	for _, e := range valid {
		if e.wildcard {
			fmt.Fprintf(&b, "    .%s 1;\n", e.domain)
		} else {
			fmt.Fprintf(&b, "    %s 1;\n", e.domain)
		}
	}
	b.WriteString("}\n")

	return b.String(), skipped
}

// WriteAllowlist atomically writes the rendered fragment to path. It writes
// to a temp file in the same directory and renames over the destination, so
// nginx's file watcher (which reacts to the file's mtime/content, KTD7)
// never observes a partially-written fragment.
func WriteAllowlist(path, fragment string) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("creating directory for %s: %w", path, err)
	}

	tmp, err := os.CreateTemp(dir, ".allowlist-*.tmp")
	if err != nil {
		return fmt.Errorf("creating temp file in %s: %w", dir, err)
	}
	tmpPath := tmp.Name()
	defer os.Remove(tmpPath) // no-op once renamed

	if _, err := tmp.WriteString(fragment); err != nil {
		tmp.Close()
		return fmt.Errorf("writing %s: %w", tmpPath, err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("closing %s: %w", tmpPath, err)
	}
	if err := os.Chmod(tmpPath, 0o644); err != nil {
		return fmt.Errorf("chmod %s: %w", tmpPath, err)
	}
	if err := os.Rename(tmpPath, path); err != nil {
		return fmt.Errorf("renaming %s to %s: %w", tmpPath, path, err)
	}
	return nil
}

// RegenerateAllowlist is the convenience entrypoint U6's CDN toggle calls:
// render the fragment for entries and atomically write it to path in one
// call.
func RegenerateAllowlist(path string, entries []AllowlistEntry) (skipped []string, err error) {
	fragment, skipped := GenerateAllowlist(entries)
	if err := WriteAllowlist(path, fragment); err != nil {
		return skipped, err
	}
	return skipped, nil
}

// looksLikeIP reports whether s parses as an IP literal -- hostnameRE would
// also reject most of these (IPv6 has colons), but IPv4 literals are valid
// hostnameRE matches and not valid CDN domains; kept separate so future
// callers can reuse the check without re-deriving it from hostnameRE.
func looksLikeIP(s string) bool {
	return net.ParseIP(s) != nil
}
